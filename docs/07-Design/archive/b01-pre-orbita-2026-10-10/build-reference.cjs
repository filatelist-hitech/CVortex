#!/usr/bin/env node
/* B01 only: derive the local reference subset from the canonical DTCG file. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '../../..');
const tokenFile = path.join(root, 'brand/tokens/cvortex.tokens.json');
const referenceFile = path.join(__dirname, 'index.html');
const cssFile = path.join(__dirname, 'tokens.css');
const manifestFile = path.join(__dirname, 'manifest.json');
const sources = [
  'docs/03-ADR/ADR-0024-git-design-reference-workflow.md',
  'docs/07-Design/Design-Foundation.md',
  'docs/07-Design/Application-Workspace.md',
  'docs/07-Design/Design-Handoff.md',
  'research/design-redesign/concept-b/index.html',
];
const consumed = [
  'surface.overlay', 'surface.canvas', 'surface.default', 'surface.elevated', 'surface.interactive',
  'text.primary', 'text.secondary', 'text.muted', 'text.disabled', 'text.inverse',
  'border.subtle', 'border.default', 'border.focus', 'border.danger',
  'accent.primary', 'accent.primaryHover', 'accent.secondary', 'accent.tertiary',
  'state.success', 'state.warning', 'state.danger', 'state.blocked',
  'state.pending', 'state.confirmed', 'state.recommended', 'state.provenance',
  'font.family.brand', 'font.family.mono', 'font.weight.regular',
  'font.weight.medium', 'font.weight.semibold', 'font.weight.bold',
  'font.size.xs', 'font.size.sm', 'font.size.md', 'font.size.lg',
  'font.size.xl', 'font.size.2xl', 'font.lineHeight.body',
  'font.lineHeight.title', 'font.tracking.label',
  'space.1', 'space.2', 'space.3', 'space.4', 'space.5', 'space.6',
  'space.8', 'space.10', 'space.12', 'radius.sm', 'radius.md', 'radius.lg',
  'radius.pill', 'motion.duration.fast', 'motion.duration.standard',
  'layer.sticky', 'layer.modal', 'breakpoint.tablet', 'breakpoint.desktop', 'breakpoint.wide',
];
const sha256 = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');

function resolver(tree) {
  function get(name, stack = []) {
    if (stack.includes(name)) throw new Error(`Cyclic token alias: ${[...stack, name].join(' -> ')}`);
    const parts = name.split('.');
    let node = tree;
    let type;
    for (const part of parts) {
      if (!node || typeof node !== 'object' || !(part in node)) throw new Error(`Missing token: ${name}`);
      node = node[part];
      type = node.$type || type;
    }
    if (!node || !('$value' in node) || !type) throw new Error(`Invalid token: ${name}`);
    const value = node.$value;
    if (typeof value === 'string' && /^\{[^{}]+\}$/.test(value)) {
      const target = get(value.slice(1, -1), [...stack, name]);
      if (target.type !== type) throw new Error(`Alias type mismatch: ${name}`);
      return target;
    }
    return { type, value };
  }
  return get;
}

function cssValue({ type, value }) {
  if (type === 'color') {
    if (!value || value.colorSpace !== 'srgb' || !/^#[0-9a-fA-F]{6}$/.test(value.hex)) throw new Error('Unsupported color');
    if (value.alpha === undefined || value.alpha === 1) return value.hex;
    if (!(value.alpha >= 0 && value.alpha <= 1)) throw new Error('Invalid alpha');
    const [r, g, b] = [1, 3, 5].map(i => parseInt(value.hex.slice(i, i + 2), 16));
    return `rgb(${r} ${g} ${b} / ${value.alpha})`;
  }
  if (type === 'dimension' || type === 'duration') {
    if (!value || !Number.isFinite(value.value) || !(type === 'dimension' ? ['px', 'rem'].includes(value.unit) : value.unit === 'ms' && value.value >= 0)) throw new Error('Unsupported dimension');
    return `${value.value}${value.unit}`;
  }
  if (type === 'fontFamily') {
    if (!Array.isArray(value) || !value.every(x => typeof x === 'string')) throw new Error('Invalid font family');
    return value.map(x => /\s/.test(x) ? `"${x.replaceAll('"', '\\"')}"` : x).join(', ');
  }
  if (type === 'fontWeight' || type === 'number') {
    if (!Number.isFinite(value)) throw new Error('Invalid number');
    return String(value);
  }
  throw new Error(`Unsupported token type: ${type}`);
}

function generate(tree, sourceHash) {
  const get = resolver(tree);
  const lines = consumed.map(name => `  --cv-${name.replaceAll('.', '-').replace(/[A-Z]/g, c => `-${c.toLowerCase()}`)}: ${cssValue(get(name))};`);
  return `/* Generated by build-reference.cjs from brand/tokens/cvortex.tokens.json. */\n:root {\n${lines.join('\n')}\n  --cv-token-source-sha256: "${sourceHash}";\n}\n`;
}

function main(mode) {
  if (!['--write', '--check'].includes(mode)) throw new Error('Usage: node build-reference.cjs --write|--check');
  const expected = generate(JSON.parse(fs.readFileSync(tokenFile, 'utf8')), sha256(tokenFile));
  const generated = {
    canonicalTokenPath: 'brand/tokens/cvortex.tokens.json',
    canonicalTokenSha256: sha256(tokenFile),
    activeReferenceSha256: sha256(referenceFile),
    referenceAssetSha256: Object.fromEntries(['app.js', 'style.css', 'build-reference.cjs', 'preview-server.cjs', 'assets/career-vortex-v1.png', 'assets/sources.json', 'assets/lucide-LICENSE.txt'].map(file => [file, sha256(path.join(__dirname, file))])),
    sourceSha256: Object.fromEntries(sources.map(file => [file, sha256(path.join(root, file))])),
    consumedTokenRoles: consumed,
  };
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  if (mode === '--write') {
    fs.writeFileSync(cssFile, expected);
    manifest.generated = generated;
    fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
  } else {
    if (fs.readFileSync(cssFile, 'utf8') !== expected) throw new Error('tokens.css drift');
    if (JSON.stringify(manifest.generated) !== JSON.stringify(generated)) throw new Error('manifest source/hash drift');
    const html = fs.readFileSync(referenceFile, 'utf8');
    for (const file of ['tokens.css', 'style.css', 'app.js', 'assets/career-vortex-v1.png']) {
      if (!html.includes(`"./${file}"`) || !fs.existsSync(path.join(__dirname, file))) throw new Error(`Missing local asset: ${file}`);
    }
    const style = fs.readFileSync(path.join(__dirname, 'style.css'), 'utf8');
    if (/https?:\/\/|@import|url\(/i.test(style)) throw new Error('External CSS asset detected');
    const tokens = resolver(JSON.parse(fs.readFileSync(tokenFile, 'utf8')));
    for (const role of ['tablet', 'desktop', 'wide']) {
      const value = tokens(`breakpoint.${role}`).value.value;
      if (!style.includes(`${value - 1}px`) && !style.includes(`${value}px`)) throw new Error(`Breakpoint drift: ${role}`);
    }
    if (/https?:\/\/|\bfetch\s*\(|XMLHttpRequest|WebSocket/i.test([html, fs.readFileSync(path.join(__dirname, 'app.js'), 'utf8')].join('\n'))) throw new Error('External/API reference detected');
  }
  console.log(`B01 reference ${mode.slice(2)}: PASS; canonical token sha256 ${generated.canonicalTokenSha256}`);
}

if (require.main === module) {
  try { main(process.argv[2]); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { resolver, cssValue, generate };
